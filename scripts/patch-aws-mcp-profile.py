#!/usr/bin/env python3
"""Patch existing JSON MCP configurations without changing unrelated servers."""
import argparse
import json
import os
from pathlib import Path
import shutil
import sys

def update(path: Path, profile: str) -> str:
    if not path.is_file():
        return "not found"
    original = path.read_text(encoding="utf-8")
    try:
        data = json.loads(original)
    except json.JSONDecodeError as exc:
        return f"skipped invalid JSON: {exc}"
    servers = data.get("mcpServers")
    if not isinstance(servers, dict) or "aws-mcp" not in servers:
        return "no aws-mcp entry"
    server = servers["aws-mcp"]
    if not isinstance(server, dict):
        return "invalid aws-mcp entry"
    env = server.setdefault("env", {})
    if not isinstance(env, dict):
        return "invalid env: manual review required"
    existing = env.get("AWS_MCP_PROXY_PROFILES")
    if existing and profile not in str(existing).split():
        return f"conflicting existing profiles: {existing}; manual review required"
    if existing == profile:
        return "already configured"
    env["AWS_MCP_PROXY_PROFILES"] = profile
    # Preserve all parsed fields, create backup before atomic write.
    backup = path.with_suffix(path.suffix + ".aws-agent-toolkit.bak")
    shutil.copy2(path, backup)
    temp = path.with_name(path.name + ".tmp")
    try:
        temp.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        os.chmod(temp, path.stat().st_mode & 0o777)
        os.replace(temp, path)
    finally:
        if temp.exists():
            temp.unlink()
    return f"updated; backup at {backup}"

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--profile", default="ring-guardian")
    parser.add_argument("paths", nargs="*", help="Explicit JSON MCP config paths")
    args = parser.parse_args()
    paths = [Path(p).expanduser() for p in args.paths]
    if not paths:
        home = Path.home()
        paths = [
            home / ".claude.json",
            home / ".cursor/mcp.json",
            home / ".codex/config.json",
            home / ".config/claude/claude_desktop_config.json",
        ]
    changed = False
    for path in paths:
        status = update(path, args.profile)
        print(f"{path}: {status}")
        changed |= status.startswith("updated") or status == "already configured"
    if not changed:
        print("No supported AWS MCP JSON config verified. Locate the file generated by the installer; pass its path explicitly. OpenCode/TOML require manual schema-specific configuration.", file=sys.stderr)
        return 2
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
